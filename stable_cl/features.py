r"""Degree-balanced polynomial features and zero-initialised classifier expansion.

The classifier is linear in a polynomial feature vector :math:`\phi(x) \in \mathbb{R}^p`, whose
coordinates are ordered by degree (degree 0, then 1, then 2, ...).  Because of that ordering, the
features available in an early experience are a *prefix* of those available later, which is what
makes progressive expansion (:func:`expand`) loss-free.
"""

from __future__ import annotations

from itertools import combinations_with_replacement
from math import comb, sqrt

import numpy as np

N_GROUPS = 4  # degree groups 0..3 (constant, linear, quadratic, cubic)


def poly_features(x, degree=3, chunk=256):
    r"""Degree-balanced polynomial feature map, ordered by degree.

    For an input :math:`x \in \mathbb{R}^n` every monomial of total degree
    :math:`k \le \text{degree}` is one feature.  A monomial is described by an exponent vector
    :math:`e \in \mathbb{N}^n` with :math:`|e| = \sum_i e_i = k`, and

    .. math::

        \phi_e(x) = s_{|e|} \prod_{i=1}^{n} x_i^{e_i},
        \qquad
        s_0 = 1,
        \quad
        s_k = \binom{n + k - 1}{k}^{-1/2} \quad (k \ge 1).

    The monomials of degree :math:`k` are generated by ``combinations_with_replacement`` over the
    ``n`` coordinates, so there are :math:`\binom{n+k-1}{k}` of them.  The total number of features
    is therefore

    .. math::

        p = \sum_{k=0}^{\text{degree}} \binom{n + k - 1}{k}
          = \binom{n + \text{degree}}{\text{degree}}.

    (For ``n = 16`` and ``degree = 3`` this is :math:`1 + 16 + 136 + 816 = 969`.)

    The scale :math:`s_k` divides each degree group by the square root of its size, so that no
    degree dominates the feature norm merely because it contains more monomials ("degree-balanced").
    Features are ordered by degree so that the features of degree :math:`\le k` form a prefix of
    the full vector; see :func:`expand`.

    Parameters
    ----------
    x : ndarray, shape (m, n)
        Input rows.
    degree : int, default 3
        Maximum total degree.
    chunk : int, default 256
        Number of rows processed at a time (memory bound only; does not change the result).

    Returns
    -------
    Phi : ndarray, shape (m, p)
        Feature matrix, column order: degree 0, then 1, ..., then ``degree``.
    deg : ndarray of int, shape (p,)
        ``deg[j]`` is the total degree of feature ``j`` (non-decreasing).
    """
    n = x.shape[1]
    exps = [np.zeros(n, int)]
    for d in range(1, degree + 1):
        exps += [
            np.bincount(c, minlength=n)
            for c in combinations_with_replacement(range(n), d)
        ]
    E = np.array(exps)
    deg = E.sum(1)
    scale = np.array([1.0 if d == 0 else 1 / sqrt(comb(n + d - 1, d)) for d in deg])
    Phi = np.concatenate(
        [
            np.prod(x[i : i + chunk, None, :] ** E[None], axis=2) * scale
            for i in range(0, len(x), chunk)
        ]
    )
    return Phi, deg


def expand(W, count):
    r"""Grow the classifier to ``count`` features by appending zero rows.

    .. math::

        W_{\text{new}} = \begin{bmatrix} W_{\text{old}} \\ 0 \end{bmatrix}.

    Since :math:`\phi_{\text{old}}(x)` is a prefix of :math:`\phi_{\text{new}}(x)`,

    .. math::

        \phi_{\text{new}}(x)^\top W_{\text{new}} = \phi_{\text{old}}(x)^\top W_{\text{old}},

    so every logit, and hence every prediction, is unchanged by the expansion.  The new rows
    start learning from zero.

    Parameters
    ----------
    W : ndarray, shape (p_old, K)
        Current weights.
    count : int
        New number of features, ``count >= p_old``.

    Returns
    -------
    ndarray, shape (count, K)
        New weight matrix (a new array; ``W`` is not modified) with the same dtype as ``W``.
    """
    return np.vstack([W, np.zeros((count - len(W), W.shape[1]), W.dtype)])
